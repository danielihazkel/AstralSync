// Bake the world's land outline into lib/worldOutline.ts for the
// astrocartography map — an SVG path in an equirectangular frame
// (viewBox 0 0 360 180: x = longitude + 180, y = 90 − latitude), so the app
// draws the map offline with no tile server and no runtime dependency.
//
// Source: Natural Earth 1:110m land (public domain), as TopoJSON from the
// world-atlas package (ISC). Download it once and pass its path:
//
//   curl -o land-110m.json https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-110m.json
//   node scripts/generate-world-outline.mjs land-110m.json
//
// The input is read as data (JSON.parse) and only numbers are written out.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const input = process.argv[2];
if (!input) {
  console.error("usage: node scripts/generate-world-outline.mjs <land-110m.json>");
  process.exit(1);
}

const topo = JSON.parse(readFileSync(input, "utf8"));
const { scale, translate } = topo.transform;

// Delta-decoded, de-quantized arcs: [[lng, lat], ...].
const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});

function ring(indices) {
  const points = [];
  for (const i of indices) {
    const arc = i >= 0 ? arcs[i] : [...arcs[~i]].reverse();
    points.push(...(points.length === 0 ? arc : arc.slice(1)));
  }
  return points;
}

/**
 * A ring that crosses the antimeridian jumps ±360° between neighbouring
 * points; drawn as is, it closes straight across the whole map. Unwrap the
 * longitudes so the ring is continuous. A ring that circles a pole
 * (Antarctica) ends a full turn from where it began: close it along the
 * pole's edge. Either way it may now run past ±180°, so the caller also
 * draws it shifted by a turn and lets the viewBox clip.
 */
function unwrap(points) {
  const out = [points[0].slice()];
  for (let i = 1; i < points.length; i++) {
    let [lng, lat] = points[i];
    const prev = out[i - 1][0];
    while (lng - prev > 180) lng -= 360;
    while (lng - prev < -180) lng += 360;
    out.push([lng, lat]);
  }
  const drift = out[out.length - 1][0] - out[0][0];
  if (Math.abs(drift) > 180) {
    const poleLat = out.reduce((s, p) => s + p[1], 0) < 0 ? -90 : 90;
    out.push([out[out.length - 1][0], poleLat], [out[0][0], poleLat]);
  }
  return out;
}

const round = (v) => Math.round(v * 10) / 10;
const parts = [];
function emit(points) {
  const pts = points.map(([lng, lat]) => [round(lng + 180), round(90 - lat)]);
  // Drop consecutive duplicates left by the rounding.
  const kept = pts.filter((p, i) => i === 0 || p[0] !== pts[i - 1][0] || p[1] !== pts[i - 1][1]);
  if (kept.length < 3) return;
  parts.push(`M${kept.map(([x, y]) => `${x} ${y}`).join("L")}Z`);
}
for (const geometry of topo.objects.land.geometries) {
  const polygons =
    geometry.type === "Polygon" ? [geometry.arcs] : geometry.type === "MultiPolygon" ? geometry.arcs : [];
  for (const polygon of polygons) {
    for (const r of polygon) {
      const points = unwrap(ring(r));
      emit(points);
      const lngs = points.map((p) => p[0]);
      if (Math.max(...lngs) > 180) emit(points.map(([lng, lat]) => [lng - 360, lat]));
      if (Math.min(...lngs) < -180) emit(points.map(([lng, lat]) => [lng + 360, lat]));
    }
  }
}

const out = `// Generated by scripts/generate-world-outline.mjs — do not edit by hand.
// Natural Earth 1:110m land (public domain), via world-atlas (ISC).

/** The world's land as one SVG path in an equirectangular frame:
 *  viewBox "0 0 360 180", x = longitude + 180, y = 90 − latitude. */
export const WORLD_LAND_PATH =
  ${JSON.stringify(parts.join(""))};
`;

const here = path.dirname(fileURLToPath(import.meta.url));
const target = path.join(here, "..", "lib", "worldOutline.ts");
writeFileSync(target, out);
console.log(`wrote ${target} (${parts.length} rings, ${out.length} bytes)`);
